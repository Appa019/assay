#!/usr/bin/env python3
"""Builds the Assay application mark.

The mark is an isometric hexagon subdivided into a rhombic lattice — the unit
cell of a crystal, drawn as a wireframe, with two cells lit off-centre. It is
abstract by design and carries no relation to the word "assay".

Geometry is computed once here and emitted twice: as SVG for the favicon, and
as PNG (supersampled, then reduced with LANCZOS) for iOS and the web manifest.
Regenerate with `python scripts/build_icon.py`; never hand-edit the assets.

Requires Pillow.
"""

from __future__ import annotations

import math
from pathlib import Path

from PIL import Image, ImageDraw

REPO_ROOT = Path(__file__).resolve().parent.parent
FRONTEND = REPO_ROOT / "frontend"

# Field is a near-black tinted toward the neutral hue of the design system.
# The accent is --accent lifted in lightness so it holds contrast on the field.
FIELD: tuple[int, int, int] = (6, 10, 17)
TEAL: tuple[int, int, int] = (0, 180, 195)
TEAL_DIM: tuple[int, int, int] = (0, 137, 152)

VIEWBOX = 180.0
CX = CY = 90.0
RADIUS = 62.0
CORNER_RADIUS = 40

# Stroke weights and opacities, in viewBox units.
W_INNER, O_INNER = 1.7, 0.30
W_SPOKE, O_SPOKE = 2.0, 0.52
W_HEX, O_HEX = 2.6, 0.88

SUPERSAMPLE = 2048

Point = tuple[float, float]


def _polar(radius: float, degrees: float) -> Point:
    angle = math.radians(degrees)
    return (CX + radius * math.cos(angle), CY - radius * math.sin(angle))


def _midpoint(a: Point, b: Point) -> Point:
    return ((a[0] + b[0]) / 2, (a[1] + b[1]) / 2)


VERTICES = {d: _polar(RADIUS, d) for d in (30, 90, 150, 210, 270, 330)}
CENTRE: Point = (CX, CY)
HEXAGON = [VERTICES[d] for d in (30, 90, 150, 210, 270, 330)]

# The three parallelogram faces of an isometric cube seen corner-on.
FACES = (
    (CENTRE, VERTICES[30], VERTICES[90], VERTICES[150]),
    (CENTRE, VERTICES[150], VERTICES[210], VERTICES[270]),
    (CENTRE, VERTICES[270], VERTICES[330], VERTICES[30]),
)


def _subdivide(
    p0: Point, p1: Point, p2: Point, p3: Point
) -> tuple[list[tuple[Point, ...]], list[tuple[Point, Point]]]:
    m01, m12 = _midpoint(p0, p1), _midpoint(p1, p2)
    m23, m30 = _midpoint(p2, p3), _midpoint(p3, p0)
    centre = _midpoint(p0, p2)
    cells = [
        (p0, m01, centre, m30),
        (m01, p1, m12, centre),
        (centre, m12, p2, m23),
        (m30, centre, m23, p3),
    ]
    return cells, [(m01, m23), (m30, m12)]


CELLS: list[list[tuple[Point, ...]]] = []
INNER_LINES: list[tuple[Point, Point]] = []
for _face in FACES:
    _cells, _lines = _subdivide(*_face)
    CELLS.append(_cells)
    INNER_LINES += _lines

# Lit cells. Asymmetric on purpose: a symmetric fill reads as ornament.
FILLED = ((0, 1, TEAL), (2, 2, TEAL_DIM))
SPOKES = tuple((CENTRE, VERTICES[d]) for d in (30, 150, 270))


def build_svg(corner_radius: int = CORNER_RADIUS) -> str:
    """Returns the mark as a standalone SVG document."""

    def fmt(value: float) -> str:
        return f"{value:.2f}"

    lines = [
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 180 180" width="180"'
        ' height="180" role="img" aria-label="Assay">',
        "  <!-- Isometric hexagon subdivided into a rhombic lattice. Two cells are",
        "       lit off-centre: a symmetric fill reads as ornament, an asymmetric",
        "       one reads as a signal. Generated by scripts/build_icon.py. -->",
        f'  <rect width="180" height="180" rx="{corner_radius}" fill="#060a11"/>',
        '  <g fill="none" stroke-linecap="round" stroke-linejoin="round">',
    ]
    for face_index, cell_index, colour in FILLED:
        points = " ".join(f"{fmt(x)},{fmt(y)}" for x, y in CELLS[face_index][cell_index])
        lines.append(
            f'    <polygon points="{points}" fill="#{colour[0]:02x}{colour[1]:02x}'
            f'{colour[2]:02x}" stroke="none"/>'
        )
    for start, end in INNER_LINES:
        lines.append(
            f'    <line x1="{fmt(start[0])}" y1="{fmt(start[1])}"'
            f' x2="{fmt(end[0])}" y2="{fmt(end[1])}" stroke="#ffffff"'
            f' stroke-opacity="{O_INNER}" stroke-width="{W_INNER}"/>'
        )
    for start, end in SPOKES:
        lines.append(
            f'    <line x1="{fmt(start[0])}" y1="{fmt(start[1])}"'
            f' x2="{fmt(end[0])}" y2="{fmt(end[1])}" stroke="#ffffff"'
            f' stroke-opacity="{O_SPOKE}" stroke-width="{W_SPOKE}"/>'
        )
    hexagon = " ".join(f"{fmt(x)},{fmt(y)}" for x, y in HEXAGON)
    lines += [
        f'    <polygon points="{hexagon}" stroke="#ffffff"'
        f' stroke-opacity="{O_HEX}" stroke-width="{W_HEX}"/>',
        "  </g>",
        "</svg>",
        "",
    ]
    return "\n".join(lines)


def build_png(size: int, scale: float = 1.0) -> Image.Image:
    """Rasterises the mark at `size` px. `scale` below 1 shrinks the mark toward
    the centre, which is how the Android maskable safe zone is honoured."""
    unit = SUPERSAMPLE / VIEWBOX
    canvas = Image.new("RGBA", (SUPERSAMPLE, SUPERSAMPLE), FIELD + (255,))

    def project(point: Point) -> Point:
        x = (point[0] - CX) * scale + CX
        y = (point[1] - CY) * scale + CY
        return (x * unit, y * unit)

    def composite(paint) -> None:
        nonlocal canvas
        layer = Image.new("RGBA", (SUPERSAMPLE, SUPERSAMPLE), (0, 0, 0, 0))
        paint(ImageDraw.Draw(layer))
        canvas = Image.alpha_composite(canvas, layer)

    def stroke_width(weight: float) -> int:
        return max(1, int(weight * unit * scale))

    def paint_cells(draw: ImageDraw.ImageDraw) -> None:
        for face_index, cell_index, colour in FILLED:
            draw.polygon(
                [project(p) for p in CELLS[face_index][cell_index]],
                fill=colour + (255,),
            )

    def paint_inner(draw: ImageDraw.ImageDraw) -> None:
        width = stroke_width(W_INNER)
        for start, end in INNER_LINES:
            draw.line(
                [project(start), project(end)],
                fill=(255, 255, 255, int(255 * O_INNER)),
                width=width,
            )

    def paint_spokes(draw: ImageDraw.ImageDraw) -> None:
        width = stroke_width(W_SPOKE)
        for start, end in SPOKES:
            draw.line(
                [project(start), project(end)],
                fill=(255, 255, 255, int(255 * O_SPOKE)),
                width=width,
            )

    def paint_hexagon(draw: ImageDraw.ImageDraw) -> None:
        outline = [project(p) for p in HEXAGON]
        draw.line(
            outline + [outline[0]],
            fill=(255, 255, 255, int(255 * O_HEX)),
            width=stroke_width(W_HEX),
            joint="curve",
        )

    composite(paint_cells)
    composite(paint_inner)
    composite(paint_spokes)
    composite(paint_hexagon)
    return canvas.resize((size, size), Image.LANCZOS)


ICO_SIZES = (16, 32, 48, 64, 128, 256)


def build_ico(path: Path) -> None:
    """Writes a multi-resolution .ico. Each frame is rendered from the geometry
    rather than downscaled from one bitmap, so the 16px frame keeps its edges."""
    frames = [build_png(size).convert("RGBA") for size in ICO_SIZES]
    largest = frames[-1]
    largest.save(path, format="ICO", sizes=[(s, s) for s in ICO_SIZES], append_images=frames[:-1])


def main() -> None:
    """Writes every icon asset the app references."""
    svg = build_svg()
    (FRONTEND / "src/app/icon.svg").write_text(svg)
    (FRONTEND / "public/icon.svg").write_text(svg)

    # iOS applies its own squircle mask, so these fill the square edge to edge.
    build_png(180).convert("RGB").save(FRONTEND / "src/app/apple-icon.png")
    build_png(192).convert("RGB").save(FRONTEND / "public/icon-192.png")
    build_png(512).convert("RGB").save(FRONTEND / "public/icon-512.png")
    # Android crops maskable icons to a circle of 80% width; stay inside it.
    build_png(512, scale=0.78).convert("RGB").save(FRONTEND / "public/icon-maskable-512.png")
    # Next lists favicon.ico ahead of icon.svg, so a stale .ico wins the tab.
    build_ico(FRONTEND / "src/app/favicon.ico")
    print("Wrote icon.svg, apple-icon.png, icon-192/512.png, icon-maskable-512.png, favicon.ico")


if __name__ == "__main__":
    main()
